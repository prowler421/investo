def _absence(history: FinancialHistory, metric: Metric, title: str) -> str | None:
    """A stated reason when the metric's own coverage explains the gap, else ``None``.

    Returning ``None`` leaves the point-count rule in ``charts.build`` to decide. The distinction is
    the one ``docs/m3/01-charts.md`` §5 asks for: *"no operating income, because banks do not report
    one"* and *"only one annual period in the window"* both produce no chart and mean different
    things, and only the coverage report knows which.
    """
    coverage = history.coverage.for_bucket(Bucket.ANNUAL).get(metric)
    if coverage is None or coverage.filled > 0:
        return None
    if history.coverage.spine.origin != "filings":
        return (
            f"{title} not charted — this filer has no periodic filings in the window, so there is "
            "no reporting calendar to chart against. See § Caveats, data coverage."
        )
    return (
        f"{title} not charted — {metric} has {coverage.filled} of {coverage.expected} annual "
        "periods. See § Caveats, data coverage."
    )


def _caveats(history: FinancialHistory) -> Caveats:
    spine = history.coverage.spine
    origin = str(spine.origin)
    return Caveats(
        coverage=_coverage_table(history),
        spine_origin=(
            f"{origin} — {fmt.count(len(spine.annual_ends))} annual and "
            f"{fmt.count(len(spine.quarterly_ends))} quarterly period ends"
        ),
        spine_warning=(
            "The denominator is observed from the facts themselves rather than from a filing "
            "calendar, which makes every percentage below circular. Read them as a description of "
            "what was tagged, not as a measurement of what is missing."
            if origin == "observed"
            else ""
        ),
        absent_sections=ABSENT_SECTIONS,
        accuracy=(
            "No forecast has been made, so no accuracy has been measured. Walk-forward "
            "backtesting against naive baselines arrives with ROADMAP M7; until it does, any "
            "confidence figure this tool prints would be unvalidated and is therefore not printed."
        ),
        gates=_gates(history),
        findings=tuple(
            Row(label=finding.code, cells=(finding.detail,), note=str(finding.metric or ""))
            for finding in history.coverage.findings
        ),
    )


def _gates(history: FinancialHistory) -> tuple[str, ...]:
    """§6.10's and §5.1's thresholds, **recorded and not enforced**.

    Both suppress a *valuation*, and there is no valuation at M3, so they are information rather
    than consequence and the wording says so. M2 recorded them for exactly this reason and made no
    refusal; repeating the refusal here would be the second copy of a rule M4 and M5 own.
    """
    notices: list[str] = []
    sic = history.sic
    if sic is not None and (6000 <= sic <= 6499 or sic == 6798):
        notices.append(
            f"SIC {sic} is a bank, insurer or REIT. DESIGN §6.10 omits the valuation for these "
            "rather than filling it with a wrong number — a gate that applies from ROADMAP M5."
        )
    if history.quarters_available < 12:
        notices.append(
            f"{history.quarters_available} quarters of history, below the twelve DESIGN §5.1 "
            "requires before a valuation is attempted. Also a gate that applies from ROADMAP M5."
        )
    return tuple(notices)


def _coverage_table(history: FinancialHistory) -> Table:
    rows: list[Row] = []
    for metric in _metric_order():
        annual = history.coverage.for_bucket(Bucket.ANNUAL).get(metric)
        quarterly = history.coverage.for_bucket(Bucket.QUARTERLY).get(metric)
        rows.append(
            Row(
                label=str(metric).replace("_", " "),
                cells=(_fill(annual), _fill(quarterly)),
                note=_tags(annual, quarterly),
            )
        )
    return Table(
        caption="Data coverage by metric",
        columns=("annual", "quarterly"),
        rows=tuple(rows),
        note_heading="tags used",
        footnote=(
            "filled / expected against the period spine. A metric with no tag matched shows "
            f"{fmt.ABSENT} and is not charted."
        ),
    )


def _fill(coverage: MetricCoverage | None) -> str:
    if coverage is None or coverage.expected == 0:
        return fmt.NOT_APPLICABLE
    return f"{coverage.filled}/{coverage.expected} ({fmt.percent(coverage.fill_rate)})"


def _tags(annual: MetricCoverage | None, quarterly: MetricCoverage | None) -> str:
    used: list[str] = []
    for coverage in (annual, quarterly):
        if coverage is None:
            continue
        used.extend(tag for tag in coverage.tags_used if tag not in used)
    return " → ".join(used) if used else fmt.ABSENT


def _appendix(history: FinancialHistory, run: RunInfo) -> Appendix:
    return Appendix(
        annual=_series_table(history, Bucket.ANNUAL),
        quarterly=_series_table(history, Bucket.QUARTERLY),
        provenance=_coverage_table(history),
        sources=_sources_table(history),
        config=tuple(
            Row(label=name, cells=(value,)) for name, value in sorted(run.config.items(), key=_pair)
        ),
        manifest_hash=run.manifest_hash or fmt.ABSENT,
    )


def _series_table(history: FinancialHistory, bucket: Bucket) -> Table:
    """One bucket's full table, at :func:`format.exact` precision.

    Exact rather than scaled, unlike everywhere else in the report. This is the page a reader checks
    against EDGAR, and ``391,035`` cannot be checked while ``391035000000.01`` can — which is also
    what makes the float discipline in ``charts.py`` assertable.
    """
    ends = tuple(
        sorted(
            {
                fact.period.end
                for metric in _metric_order()
                for fact in history.series(metric, bucket)
            },
            key=_day,
        )
    )
    rows: list[Row] = []
    for metric in _metric_order():
        by_end = {fact.period.end: fact for fact in history.series(metric, bucket)}
        rows.append(
            Row(
                label=str(metric).replace("_", " "),
                cells=tuple(_exact_cell(by_end.get(end)) for end in ends),
                note=_unit(by_end),
            )
        )
    return Table(
        caption=f"{str(bucket).capitalize()} series, as filed",
        columns=tuple(fmt.iso_date(end) for end in ends),
        rows=tuple(rows),
        note_heading="unit",
        footnote="Values exactly as filed — unscaled and unrounded, for checking against EDGAR.",
    )


def _exact_cell(fact: Fact | None) -> str:
    return fmt.ABSENT if fact is None else fmt.exact(fact.value)


def _unit(by_end: Mapping[date, Fact]) -> str:
    units = sorted({fact.unit for fact in by_end.values()}, key=_text)
    return ", ".join(units) if units else fmt.ABSENT


def _sources_table(history: FinancialHistory) -> Table:
    """§9.1's tag-provenance appendix, **interned by the serializer rather than re-walked here.**

    ``docs/m2/04-serialize.md`` observed that the ``sources`` array *"is also §9.1's appendix,
    already deduplicated, so M3 renders it directly instead of walking every fact to collect
    distinct refs."* Two walks would be two chances to disagree about what "distinct" means, in the
    one table whose entire job is to be checkable.
    """
    rows = tuple(
        Row(
            label=str(index),
            cells=(
                ref.accession.value,
                f"{ref.taxonomy or fmt.ABSENT}:{ref.tag or fmt.ABSENT}",
                ref.form,
                fmt.iso_date(ref.filed),
            ),
            note=ref.url,
        )
        for index, ref in enumerate(intern_sources(history))
    )
    return Table(
        caption="Sources",
        columns=("#", "accession", "taxonomy:tag", "form", "filed"),
        rows=rows,
        note_heading="url",
    )


def _sic(history: FinancialHistory) -> str:
    if history.sic is None:
        return fmt.ABSENT
    return (
        f"{history.sic} — {history.sic_description}"
        if history.sic_description
        else str(history.sic)
    )


def _latest(facts: Sequence[Fact]) -> Fact | None:
    return max(facts, key=_fact_day) if facts else None


def _metric_order() -> tuple[Metric, ...]:
    """Tier 1 then tier 2, in registry order — the order ``investo facts`` prints."""
    return (*metrics_in_tier(Tier.DCF), *metrics_in_tier(Tier.QUALITY))


def _pair(item: tuple[str, str]) -> str:
    return item[0]


def _text(value: str) -> str:
    return value
