"""``ReportModel`` — everything a template is allowed to see (ROADMAP M3, DESIGN.md §9.1).

**Every leaf below is a ``str``, a ``bool``, an ``int``, a :class:`~investo.report.charts.ChartImage`
or a sequence of those. No ``Decimal`` and no ``Fact`` reaches a template.** That single rule is
CLAUDE.md convention 14, and three guarantees fall out of it rather than needing to be checked:

- **A template cannot compute a figure**, because the figure is already a string. A number computed
  in a template has no ``Fact`` behind it, is absent from ``report.json``, and is invisible to every
  test that walks this model — and it is the most natural thing to write when the template is two
  lines from the data. The AST check over the template source is a second lock on a door this
  module already shut.
- **The appendix cannot disagree with an axis label**, because both are produced by
  :mod:`investo.report.format` from the same ``Decimal``.
- **Everything printable is decided in Python**, where it is unit-testable without rendering
  anything — which matters because rendering costs a WeasyPrint import and a PDF.

This module is also where the three *derived* series live. Free cash flow, the margins and the
year-over-year growth rate are computed here, over ``Decimal``, each producing a
:class:`~investo.domain.provenance.Derivation` naming both inputs — so a point on a chart traces
exactly like a filed value. They are not computed in ``charts.py`` (a chart module that does
arithmetic can print a number nothing else knows about) and not in ``normalize/`` (they are
presentation, and §3.2's ``FinancialHistory`` is a record of what was *filed*).

**Both inputs are required, per period, with no interpolation.** A margin for a year with revenue
and no gross profit is not computed and not plotted; the point is dropped. Carrying the previous
year's numerator forward would draw a flat segment that reads as stability and means "missing".
"""

