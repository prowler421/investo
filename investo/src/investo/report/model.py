def free_cash_flow(history: FinancialHistory, bucket: Bucket) -> tuple[Datum, ...]:
    """``OPERATING_CASH_FLOW − CAPEX``, per period, both required.

    Capex is positive-as-filed — ``normalize/tags.py`` declares the sign convention and
    ``docs/m2/01-tags.md`` §8 argues it — so this subtracts rather than adds. Getting that backwards
    produces a series that is wrong by twice capex and looks entirely plausible, which is why the
    convention lives in the registry and is not re-decided here.
    """
    cash = {fact.period.end: fact for fact in history.series(Metric.OPERATING_CASH_FLOW, bucket)}
    capex = {fact.period.end: fact for fact in history.series(Metric.CAPEX, bucket)}
    return tuple(
        Datum(
            value=cash[end].value - capex[end].value,
            period=cash[end].period,
            source=Derivation(
                rule="free_cash_flow",
                inputs=(cash[end].source, capex[end].source),
                note="operating cash flow less capital expenditure, capex positive as filed",
            ),
        )
        for end in sorted(set(cash) & set(capex), key=_day)
    )


def margin_series(
    history: FinancialHistory, numerator: Metric, bucket: Bucket
) -> tuple[Datum, ...]:
    """``numerator ÷ REVENUE``, per period, both required and revenue non-zero.

    A margin against zero revenue is undefined rather than infinite, and a pre-revenue biotech is a
    real filer — dropping the period is the only answer that does not print something.
    """
    revenue = {fact.period.end: fact for fact in history.series(Metric.REVENUE, bucket)}
    top = {fact.period.end: fact for fact in history.series(numerator, bucket)}
    return tuple(
        Datum(
            value=top[end].value / revenue[end].value,
            period=top[end].period,
            source=Derivation(
                rule="margin",
                inputs=(top[end].source, revenue[end].source),
                note=f"{numerator} / revenue",
            ),
        )
        for end in sorted(set(revenue) & set(top), key=_day)
        if revenue[end].value != 0
    )


def yoy_series(facts: Sequence[Fact]) -> tuple[Datum, ...]:
    """``(vₜ − vₜ₋₁) ÷ vₜ₋₁`` over **consecutive** periods in the series as given.

    Consecutive in the series, not consecutive in the calendar: a filer with a gap year would
    otherwise get a two-year growth rate labelled as one year's, which overstates it by roughly the
    square. The gap is visible on the chart as a missing point, which is the honest rendering.
    """
    ordered = sorted(facts, key=_fact_day)
    return tuple(
        Datum(
            value=(later.value - earlier.value) / earlier.value,
            period=later.period,
            source=Derivation(
                rule="yoy_growth",
                inputs=(later.source, earlier.source),
                note=f"{earlier.period.end.isoformat()} → {later.period.end.isoformat()}",
            ),
        )
        for earlier, later in pairwise(ordered)
        if earlier.value != 0 and _is_consecutive(earlier.period.end, later.period.end)
    )


def _is_consecutive(earlier: date, later: date) -> bool:
    """Within a year and a quarter of each other — the same ±tolerance the spine uses.

    Not `later.year - earlier.year == 1`, which is false for a filer whose fiscal year end moved by
    a week across a calendar boundary and true for one that skipped a year and shifted.
    """
    return 300 <= (later - earlier).days <= 430


def _day(value: date) -> date:
    return value


def _fact_day(fact: Fact) -> date:
    return fact.period.end


