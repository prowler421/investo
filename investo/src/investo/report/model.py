def build_model(history: FinancialHistory, run: RunInfo, *, brief: bool = False) -> ReportModel:
    """Assemble the whole document.

    ``brief`` is carried on the model and changes **nothing else**. The same sections are built with
    the same values; the template decides which of them to render. A brief report that took a
    different data path could disagree with the full one about a figure, and the disagreement would
    be visible only to someone who ran both — so the few milliseconds of formatting nobody reads are
    the price of the guarantee.
    """
    charts = _charts(history)
    cover = _cover(history)
    snapshot = _snapshot(history)
    caveats = _caveats(history)
    appendix = _appendix(history, run)
    used = tuple(source for chart in charts for source in chart.sources) + tuple(
        fact.source
        for store in (history.annual, history.quarterly)
        for facts in store.values()
        for fact in facts
    )
    return ReportModel(
        cover=cover,
        snapshot=snapshot,
        history=HistorySection(charts=charts, omissions=(_MISSING_ROIC,)),
        caveats=caveats,
        appendix=appendix,
        run=run,
        brief=brief,
        sources_used=used,
    )


def _cover(history: FinancialHistory) -> Cover:
    rate = history.coverage.tier_fill_rate(Tier.DCF, Bucket.ANNUAL)
    origin = str(history.coverage.spine.origin)
    qualifier = " against an observed denominator" if origin == "observed" else ""
    return Cover(
        ticker=history.ticker,
        name=history.name,
        as_of=fmt.iso_date(history.as_of),
        verdict=NOT_ASSESSED,
        verdict_note="Score and confidence rating arrive with the forecast engine (ROADMAP M5).",
        confidence=NOT_ASSESSED,
        confidence_note=(
            "No partial rating is shown. Three of the five inputs DESIGN §9.2 names exist today; "
            "a number built from three of five reads on the same scale as the real one."
        ),
        coverage_line=f"Tier-1 annual coverage {fmt.percent(rate)}{qualifier}",
        quarters_line=f"{fmt.count(history.quarters_available)} quarters of history",
        disclaimer=DISCLAIMER,
    )


def _snapshot(history: FinancialHistory) -> Snapshot:
    rows: list[Row] = [
        Row(label="CIK", cells=(str(history.cik),)),
        Row(label="SIC", cells=(_sic(history),)),
        Row(label="Fiscal year end", cells=(history.fiscal_year_end or fmt.ABSENT,)),
        Row(
            label="Window",
            cells=(f"{fmt.iso_date(history.window[0])} to {fmt.iso_date(history.window[1])}",),
        ),
        Row(label="Quarters available", cells=(fmt.count(history.quarters_available),)),
    ]
    for metric, label in _SNAPSHOT_METRICS:
        latest = _latest(history.series(metric, Bucket.ANNUAL))
        rows.append(
            Row(
                label=f"{label} (latest FY)",
                cells=(fmt.money(latest.value) if latest is not None else fmt.ABSENT,),
                note=fmt.iso_date(latest.period.end) if latest is not None else "",
            )
        )
    fcf = free_cash_flow(history, Bucket.ANNUAL)
    rows.append(
        Row(
            label="Free cash flow (latest FY)",
            cells=(fmt.money(fcf[-1].value) if fcf else fmt.ABSENT,),
            note="derived: operating cash flow − capex" if fcf else "",
        )
    )

    cap, note = fmt.ABSENT, ""
    if history.market_cap is not None:
        value, derivation = history.market_cap
        cap = fmt.money(value)
        note = derivation.note or derivation.rule
    return Snapshot(
        rows=tuple(rows),
        market_cap=cap,
        market_cap_note=note,
        omissions=(_MISSING_COHORT, _MISSING_DESCRIPTION),
    )


